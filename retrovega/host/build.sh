#!/bin/sh
# rvsim: a RetroVega flight with the game's logic and nothing else, on the host or in a browser (docs/logic.md,
# "The host harness").  The logic and the modules it shares are src/'s, unchanged; host/ has the rest.
#   host/build.sh             build/host32/rvsim: 32-bit (int 32, long 32), UBSan, the SDL2 window; and beside it
#                             playtest, the play tests (tests/play/playtest.c, docs/gameplay.md)
#   ARCH=64                   64-bit (long 64: what code written with long, not int32_t, does there)
#   SAN=ubsan|asan|none       the checks built in: UBSan (the default); ASan with UBSan; none (for valgrind)
#   CC=clang                  clang, which adds its implicit-truncation check: a value that does not fit the
#                             int16_t (or uint16_t...) it is stored in, the 16-bit overflow DOS would wrap
#   SDL=0                     headless only (no SDL2 needed)
#   OPT=-O0                   the optimisation (default -O1; always -g3: gdb knows the slot arrays' macros)
#   LOGIC=path/to/logic.c     another logic.c in src/logic.c's place (an experiment, a test's)
#   WEB=1                     the browser build with Emscripten (build/hostweb/: index.html, rvsim.js, .wasm, .data)
# The directory says which: build/host32, build/host64-asan, build/host32-clang, build/host32-none-nosdl, ...
# Needs: gcc (and gcc-multilib for 32-bit), python3, SDL2 (libsdl2-dev, and libsdl2-dev:i386 for 32-bit);
# WEB=1 the Emscripten SDK (emcc on PATH, or EMSDK=/path/to/emsdk).
set -e
cd "$(dirname "$0")/.."
ARCH=${ARCH:-32}
SAN=${SAN:-ubsan}
CC=${CC:-gcc}
SDL=${SDL:-1}
OPT=${OPT:--O1}
case "$ARCH" in 32|64) ;; *) echo "ARCH is 32 or 64"; exit 1 ;; esac
case "$SAN" in ubsan|asan|none) ;; *) echo "SAN is ubsan, asan or none"; exit 1 ;; esac
CCNAME=$(basename "$CC")
if [ -n "${WEB:-}" ]; then
    OUT=build/hostweb
else
    OUT=build/host$ARCH
    [ "$SAN" = ubsan ] || OUT=$OUT-$SAN
    case "$CCNAME" in gcc|cc) ;; *) OUT=$OUT-$CCNAME ;; esac
    [ "$SDL" = 1 ] || OUT=$OUT-nosdl
fi
[ -z "${LOGIC:-}" ] || OUT=$OUT-$(basename "$LOGIC" .c)   # (another logic's build beside the game's)
mkdir -p "$OUT/obj" "$OUT/stubs"

# the generated sources, as build.sh makes them for DOS, and the harness's own
python3 tools/rvabi.py --c-header > src/rvhooks.h
python3 tools/rvdata.py --out "$OUT/RVGAME.DAT" --header src/rvdata.h > /dev/null
cp data/shapes.dat "$OUT/SHAPES.DAT"
python3 tools/rvabi.py --host-thunks > "$OUT/thunks.c"
rm -f "$OUT"/stubs/*.c
python3 tools/rvabi.py --stubs "$OUT/stubs"
python3 - "$OUT/palette.h" <<'EOF'
import json, sys
rgb = json.load(open('data/palette.json'))['rgb']
with open(sys.argv[1], 'w') as f:
    f.write('/* the flight\'s palette (data/palette.json): generated by host/build.sh */\n')
    f.write('static const unsigned char k_palette[256][3] = {\n')
    for i in range(0, 256, 8):
        f.write('    ' + ' '.join('{ %d, %d, %d },' % tuple(c) for c in rgb[i:i + 8]) + '\n')
    f.write('};\n')
EOF

# the game's sources as Watcom builds them: char unsigned (Watcom's), no type-based aliasing (Watcom assumes none,
# and the slot arrays are read through casts), the DOS words (host/rvhost.h)
LOGIC=${LOGIC:-src/logic.c}
SHARED="world shots collide lightfield hud campaign"
COMMON="-std=gnu99 -g3 -funsigned-char -fno-strict-aliasing -include host/rvhost.h -Isrc -Ihost -I$OUT"
WARN="-Wall -Wextra -Wno-unused-parameter -Wno-sign-compare -Wno-missing-field-initializers -Wno-unused-result
      -Wdeclaration-after-statement"     # (C89's rule: Watcom refuses a declaration after a statement)

AR=ar
EXE="$OUT/rvsim"
LINKG=-g
if [ -n "${WEB:-}" ]; then
    # the browser's: wasm32 (int and long 32 bits, as ARCH=32), no sanitizer, SDL2 from Emscripten's ports, the
    # data preloaded into its file system
    if ! command -v emcc > /dev/null; then   # (emsdk's own layout: its emsdk_env.sh wants bash)
        EMSDK=${EMSDK:-$HOME/emsdk}
        PATH="$EMSDK/upstream/emscripten:$PATH"
        export EM_CONFIG="$EMSDK/.emscripten"
    fi
    CC=emcc
    AR=emar
    ARCHF=""
    OPT=-O2
    SANF=""
    SDLF="-DHOST_SDL -sUSE_SDL=2"
    SDLL="-sUSE_SDL=2 -sALLOW_MEMORY_GROWTH=1 --preload-file $OUT/RVGAME.DAT@/RVGAME.DAT
          --preload-file $OUT/SHAPES.DAT@/SHAPES.DAT"
    EXE="$OUT/rvsim.js"
    LINKG=""                            # (no debug info in the page's wasm)
else
    ARCHF=-m$ARCH
    case "$SAN" in
        ubsan) SANF="-fsanitize=undefined -fno-sanitize=alignment" ;;
        asan) SANF="-fsanitize=address,undefined -fno-sanitize=alignment -fno-omit-frame-pointer" ;;
        none) SANF="" ;;
    esac
    # (alignment: the fixed block is DOS's, packed: randomSeed and the gun records' words sit at odd places, which x86
    # reads as well as any)
    case "$CCNAME" in clang*)
        [ "$SAN" = none ] || SANF="$SANF -fsanitize=implicit-integer-truncation"
        # (the stacks' files and lines: clang's runtime wants llvm-symbolizer, the llvm package's)
        SYM=$($CC -print-resource-dir)/../../../bin/llvm-symbolizer
        [ -x "$SYM" ] || SYM=$(command -v llvm-symbolizer || true)
        [ -n "$SYM" ] && [ -x "$SYM" ] && SANF="$SANF -DHOST_SYMBOLIZER=\":external_symbolizer_path=$SYM\"" ;;
    esac
    SDLF=""
    SDLL=""
    if [ "$SDL" = 1 ]; then
        if [ "$ARCH" = 32 ]; then
            PC="env PKG_CONFIG_LIBDIR=/usr/lib/i386-linux-gnu/pkgconfig:/usr/lib32/pkgconfig pkg-config"
        else
            PC=pkg-config
        fi
        SDLF="-DHOST_SDL $($PC --cflags sdl2)"
        SDLL=$($PC --libs sdl2)
    fi
fi
CFLAGS="$ARCHF $OPT $COMMON $WARN $SANF"
rm -f "$OUT"/obj/*.o
$CC $CFLAGS -c -o "$OUT/obj/logic.o" "$LOGIC"
for c in $SHARED; do
    $CC $CFLAGS -c -o "$OUT/obj/$c.o" "src/$c.c"
done
$CC $CFLAGS -c -o "$OUT/obj/host.o" host/host.c
$CC $CFLAGS -c -o "$OUT/obj/fixed.o" host/fixed.c
$CC $CFLAGS $SDLF -c -o "$OUT/obj/sim.o" host/sim.c
$CC $CFLAGS -c -o "$OUT/obj/thunks.o" "$OUT/thunks.c"
# the thunks' default bodies, a library: the linker takes one only where logic.c has no _impl (as on DOS)
rm -f "$OUT/libstubs.a"
for c in "$OUT"/stubs/*.c; do
    $CC $CFLAGS -c -o "${c%.c}.o" "$c"
done
$AR rcs "$OUT/libstubs.a" "$OUT"/stubs/*.o
$CC $ARCHF $OPT $SANF $LINKG -o "$EXE" "$OUT"/obj/*.o "$OUT/libstubs.a" $SDLL -lm
if [ -z "${WEB:-}" ]; then
    # the play tests (tests/play/playtest.c, docs/gameplay.md): the same objects but rvsim's own, and the tests' main
    $CC $CFLAGS -DPLAYTEST_MAIN -c -o "$OUT/playtest.o" tests/play/playtest.c
    $CC $ARCHF $OPT $SANF $LINKG -o "$OUT/playtest" $(ls "$OUT"/obj/*.o | grep -v '/sim\.o$') "$OUT/playtest.o" \
        "$OUT/libstubs.a" $SDLL -lm
fi
if [ -n "${WEB:-}" ]; then
    REV=$(git rev-parse --short HEAD)$(git diff --quiet HEAD -- src host tools || echo M)
    sed "s/@REV@/$REV/" host/web/index.html > "$OUT/index.html"
    echo "built $OUT/index.html (with rvsim.js, .wasm, .data: serve the directory)"
else
    echo "built $EXE and $OUT/playtest"
fi
