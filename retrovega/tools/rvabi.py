#!/usr/bin/env python3
"""Lay out abi/rvabi.def: the fixed DGROUP offsets, RVHOOK thunks and sites.

    rvabi.py            print the layout as Markdown tables (docs/spec.md section 4)
    rvabi.py --header   print rvabi.h for the game (#defines only)
    rvabi.py --c-header print src/rvhooks.h: every place the layer can hook,
                        typed (fixed-block data, thunk prototypes, sites)
    rvabi.py --asm      print src/rvhook.asm: RVHOOK (header, thunks, the flight
                        loop's sites from src/rvflight.inc) and the fixed
                        block's segment, for NASM -f obj -i src/
    rvabi.py --layer    print src/cpu/wcnet_rv.h: RV.EXE's hook places for the
                        layer (the RVHOOK header, every thunk's offset, name,
                        arguments and result, the sites)
    rvabi.py --stubs DIR
                        write DIR/stub_NAME.c, a default body per thunk that
                        logs its first call: built into a library, so the
                        linker takes one only where the engine has no _impl
    rvabi.py --weak-stubs           the stubs' bodies as one C file of weak symbols (desktop/gen/stubs.c)
    rvabi.py --host-thunks
                        print host/thunks.c: the host harness's thunks, each
                        calling its _impl between the harness's checks
                        (host_thunk_enter / host_thunk_leave)
    rvabi.py --column   print the RV column for src/cpu/wcnet_ds.def
    rvabi.py --splice docs/spec.md
                        put the tables between the file's <!-- rvabi --> markers

A region that grows past the next SECTION (or END) is an error: offsets
never move silently.  Arrays of 4-byte or larger elements start on a 4-byte
boundary, the rest on 2.
"""
import io
import os
import sys
from contextlib import redirect_stdout

HERE = os.path.dirname(os.path.abspath(__file__))
DEF = os.path.join(HERE, '..', 'abi', 'rvabi.def')


def num(s):
    return int(s, 0)


def parse(path):
    consts, sections, funcs, sites = {}, [], [], []
    for lineno, raw in enumerate(open(path), 1):
        line = raw.split('#', 1)[0].split()
        note = raw.split('#', 1)[1].strip() if '#' in raw else ''
        if not line:
            continue
        kind, args = line[0], line[1:]
        if kind in ('SLOTS', 'MAXSHIPSLOT', 'DGROUP_PARA'):
            consts[kind] = num(args[0])
        elif kind == 'SECTION':
            sections.append({'name': args[0], 'start': num(args[1]), 'items': []})
        elif kind == 'END':
            sections.append({'name': 'END', 'start': num(args[0]), 'items': []})
        elif kind in ('VAR', 'SLOT', 'TABLE'):
            size = num(args[1])
            count = num(args[2]) if kind == 'TABLE' else 1
            sections[-1]['items'].append({'kind': kind, 'name': args[0], 'size': size,
                                          'count': count, 'note': note})
        elif kind == 'FUNC':
            funcs.append({'name': args[0], 'args': num(args[1]), 'ret': args[2], 'note': note,
                          'off': 0x20 + 5 * len(funcs)})
        elif kind == 'SITE':
            sites.append({'name': args[0], 'off': num(args[1]), 'note': note})
        else:
            sys.exit('%s:%d: unknown line %r' % (path, lineno, kind))
    return consts, sections, funcs, sites


def layout(consts, sections):
    slots = consts['SLOTS']
    items = []
    for sec, nxt in zip(sections, sections[1:]):
        off = sec['start']
        for it in sec['items']:
            n = slots if it['kind'] == 'SLOT' else it['count']
            align = 4 if it['size'] >= 4 and it['kind'] != 'VAR' else 2
            off = (off + align - 1) & ~(align - 1)
            it['off'], it['total'] = off, it['size'] * n
            off += it['total']
            items.append(it)
        sec['end'] = off
        if off > nxt['start']:
            sys.exit('section %s ends at 0x%04X, past 0x%04X' % (sec['name'], off, nxt['start']))
    return items


def main():
    consts, sections, funcs, sites = parse(DEF)
    items = layout(consts, sections)
    if len(items) * 2 > 192:
        sys.exit('rvPuppetDirectory holds 96 entries, there are %d' % len(items))
    mode = sys.argv[1] if len(sys.argv) > 1 else ''
    if mode == '--splice':
        buf = io.StringIO()
        with redirect_stdout(buf):
            print_tables(consts, sections, funcs, sites)
        text = open(sys.argv[2]).read()
        head, rest = text.split('<!-- rvabi -->\n', 1)
        tail = rest.split('<!-- /rvabi -->', 1)[1]
        open(sys.argv[2], 'w').write(head + '<!-- rvabi -->\n' + buf.getvalue() + '<!-- /rvabi -->' + tail)
        return
    if mode == '--header':
        print('/* Generated by tools/rvabi.py from abi/rvabi.def: do not edit. */')
        print('#define RV_SLOTS %d' % consts['SLOTS'])
        print('#define RV_MAX_SHIP_SLOT %d' % consts['MAXSHIPSLOT'])
        print('#define RV_DGROUP_PARA 0x%04X' % consts['DGROUP_PARA'])
        for it in items:
            print('#define RV_DS_%s 0x%04X' % (it['name'], it['off']))
        for f in funcs:
            print('#define RV_FN_%s 0x%04X' % (f['name'], f['off']))
        for s in sites:
            print('#define RV_SITE_%s 0x%04X' % (s['name'], s['off']))
        return
    if mode == '--c-header':
        c_header(consts, sections, items, funcs, sites)
        return
    if mode == '--asm':
        asm(consts, sections, items, funcs, sites)
        return
    if mode == '--layer':
        p = print
        p('// wcnet_rv.h: RV.EXE (retrovega/, the new game) for the multiplayer layer.')
        p('// Generated by retrovega/tools/rvabi.py --layer from retrovega/abi/rvabi.def:')
        p('// do not edit.  retrovega/docs/spec.md sections 3-5, docs/engine.md.')
        p('#ifndef WCNET_RV_H_')
        p('#define WCNET_RV_H_')
        p()
        p('#define RV_EXE "RV.EXE"')
        p('#define RV_HOOK_MAGIC "RVHOOK"        // at the image\'s first paragraph')
        p('#define RV_HOOK_DGROUP 0x08           // word: DGROUP, relocated by DOS: the data segment')
        p('#define RV_SIGNATURE "%s"' % SIGNATURE)
        p('#define RV_SIGNATURE_OFF 0x%04X       // in DGROUP' % [i for i in items if i['name'] == 'aLoadingWingCom'][0]['off'])
        p('#define RV_ABI_VERSION %d' % ABI_VERSION)
        p()
        p('struct RvThunk { unsigned short off; const char *name; int nargs; bool returns; };')
        p('static const RvThunk kRvThunks[] = {')
        for f in funcs:
            p('    { 0x%04X, "%s", %d, %s },' % (f['off'], f['name'], f['args'], 'true' if f['ret'] == 'ax' else 'false'))
        p('};')
        p()
        p('struct RvSite { unsigned short off; const char *name; };')
        p('static const RvSite kRvSites[] = {')
        for st in sites:
            p('    { 0x%04X, "%s" },' % (st['off'], st['name']))
        p('};')
        p()
        p('#endif')
        return
    if mode == '--stubs':
        os.makedirs(sys.argv[2], exist_ok=True)
        for f in funcs:
            ret = 'uint16_t' if f['ret'] == 'ax' else 'void'
            args = ', '.join('uint16_t a%d' % i for i in range(f['args'])) or 'void'
            uses = ''.join(' (void)a%d;' % i for i in range(f['args']))
            body = ('    static int16_t once;%s\n    if (!once++) rv_log("stub: %s");\n%s'
                    % (uses, f['name'], '    return 0;\n' if ret != 'void' else ''))
            with open(os.path.join(sys.argv[2], 'stub_%s.c' % f['name']), 'w') as out:
                out.write('/* generated by tools/rvabi.py --stubs: the default %s */\n'
                          '#include "rv.h"\n#include "rvhooks.h"\n\n'
                          '%s __far __cdecl %s_impl(%s)\n{\n%s}\n' % (f['name'], ret, f['name'], args, body))
        return
    if mode == '--weak-stubs':
        # the same default bodies in one file, each weak: where the game has its own _impl, the linker takes that
        p = print
        p('/* desktop/gen/stubs.c: the thunks\' default bodies (each a weak symbol: the game\'s own _impl, where it has')
        p(' * one, is the one linked).  Generated by tools/rvabi.py --weak-stubs from abi/rvabi.def: do not edit (the')
        p(' * desktop Makefile\'s check-generated compares it with the generator\'s). */')
        p('#include "rv.h"')
        p('#include "rvhooks.h"')
        for f in funcs:
            ret = 'uint16_t' if f['ret'] == 'ax' else 'void'
            args = ', '.join('uint16_t a%d' % i for i in range(f['args'])) or 'void'
            uses = ''.join(' (void)a%d;' % i for i in range(f['args']))
            p()
            p('__attribute__((weak)) %s %s_impl(%s)' % (ret, f['name'], args))
            p('{')
            p('    static int16_t once;%s' % uses)
            p('    if (!once++) rv_log("stub: %s");' % f['name'])
            if ret != 'void':
                p('    return 0;')
            p('}')
        return
    if mode == '--host-thunks':
        host_thunks(funcs)
        return
    if mode == '--column':
        for it in items:
            if not it['name'].startswith('rv'):
                print('%-32s 0x%04X' % (it['name'], it['off']))
        return
    print_tables(consts, sections, funcs, sites)


CTYPE = {1: 'uint8_t', 2: 'uint16_t', 4: 'uint32_t'}
ABI_VERSION = 1
ASM_BODIES = ('autoAnimation',)        # thunks whose _impl is in src/rvflight.inc (a site inside it)
SIGNATURE = 'Loading RETROVEGA'


def c_header(consts, sections, items, funcs, sites):
    p = print
    p('/* rvhooks.h: every place the multiplayer layer (src/cpu/wcnet_*) can hook in')
    p(' * RV.EXE.  Generated by tools/rvabi.py --c-header from abi/rvabi.def: do not')
    p(' * edit.  docs/spec.md sections 4 and 5, docs/engine.md.')
    p(' *')
    p(' * Data: the fixed block at DS:0000-7FFF (DGROUP starts with it).  Each name')
    p(' * is an lvalue; per-slot arrays index by slot (0 .. RV_SLOTS-1), tables by')
    p(' * record.  Use RV_SLOT_OK() / RV_CHECK() before indexing with a variable.')
    p(' * Thunks: far cdecl entry points in RVHOOK; call them, never the _impl body,')
    p(' * so a hook on the thunk sees every call.  Sites: RVHOOK offsets of the')
    p(' * flight loop\'s hook places (rvhook.asm).  */')
    p('#ifndef RVHOOKS_H')
    p('#define RVHOOKS_H')
    p()
    p('#include "rvtypes.h"')
    p()
    p('#define RV_ABI_VERSION %d' % ABI_VERSION)
    p('#define RV_SLOTS %d' % consts['SLOTS'])
    p('#define RV_MAX_SHIP_SLOT %d' % consts['MAXSHIPSLOT'])
    p('#define RV_CAMERA_SLOT (RV_SLOTS - 3)')
    p('#define RV_SCRATCH_SLOT (RV_SLOTS - 1)')
    p('#define RV_FIXED_BYTES 0x%04X' % sections[-1]['start'])
    p('#define RV_SIGNATURE "%s"' % SIGNATURE)
    p('#define RV_SLOT_OK(s) ((uint16_t)(s) < RV_SLOTS)')
    p()
    p('/* RVHOOK header: loadSeg:0000 */')
    p('#define RVHOOK_MAGIC_OFF   0x00   /* "RVHOOK" */')
    p('#define RVHOOK_DGROUP_OFF  0x08   /* word: DGROUP\'s segment, relocated at load */')
    p('#define RVHOOK_VERSION_OFF 0x0A')
    p('#define RVHOOK_NTHUNK_OFF  0x0C')
    p('#define RVHOOK_NSITE_OFF   0x0E')
    p()
    p('typedef struct { int32_t x, y, z; } RvVec3;   /* 256 = 1 km, or 1.0 for orientations */')
    p()
    p('/* where the fixed block is: DS:0000 on DOS; the host\'s DGROUP stand-in, rv_dgroup (host/fixed.c) */')
    p('#ifdef RV_HOST')
    p('extern uint8_t rv_dgroup[];')
    p('#define RV_AT(t, off) ((t)(rv_dgroup + (off)))')
    p('#else')
    p('#define RV_AT(t, off) ((t)(off))')
    p('#endif')
    p()
    for sec in sections[:-1]:
        p('/* --- %s: 0x%04X- --- */' % (sec['name'], sec['start']))
        for it in sec['items']:
            note = (' /* %s */' % it['note'].replace('*/', '* /')) if it['note'] else ''
            off = it['off']
            n = consts['SLOTS'] if it['kind'] == 'SLOT' else it['count']
            if it['kind'] == 'VAR' and it['size'] in CTYPE:
                p('#define %-30s (*RV_AT(%s *, 0x%04X))%s' % (it['name'], CTYPE[it['size']], off, note))
            elif it['kind'] == 'SLOT' and it['size'] in CTYPE:
                p('#define %-30s RV_AT(%s *, 0x%04X)  /* [%d] */%s' % (it['name'], CTYPE[it['size']], off, n, note))
            elif it['kind'] == 'SLOT' and it['size'] == 12:
                p('#define %-30s RV_AT(RvVec3 *, 0x%04X)  /* [%d] */%s' % (it['name'], off, n, note))
            else:
                p('#define %-30s RV_AT(uint8_t *, 0x%04X)  /* %d x %d bytes */%s'
                  % (it['name'], off, n, it['size'], note))
            p('#define %-30s %d' % (it['name'] + '_SIZE', it['size']))
        p()
    p('/* --- thunks: RVHOOK offsets, and their far cdecl prototypes --- */')
    for f in funcs:
        p('#define RV_FN_%-24s 0x%04X' % (f['name'], f['off']))
    p()
    for f in funcs:
        ret = 'uint16_t' if f['ret'] == 'ax' else 'void'
        args = ', '.join(['uint16_t'] * f['args']) or 'void'
        note = (' /* %s */' % f['note']) if f['note'] else ''
        p('extern %s __far __cdecl %s(%s);%s' % (ret, f['name'], args, note))
        p('%s __far __cdecl %s_impl(%s);' % (ret, f['name'], args))
    p()
    p('/* --- sites: RVHOOK offsets in the flight loop (rvhook.asm) --- */')
    for st in sites:
        p('#define RV_SITE_%-22s 0x%04X  /* %s */' % (st['name'], st['off'], st['note']))
    p()
    p('#endif')


def host_thunks(funcs):
    p = print
    p('/* host/thunks.c: the host harness\'s stand-ins for RVHOOK\'s thunks (on DOS a `jmp far` the layer can hook).')
    p(' * Generated by tools/rvabi.py --host-thunks from abi/rvabi.def: do not edit.  Each calls its _impl between')
    p(' * host_thunk_enter and host_thunk_leave (host/host.c: the trace, the checks of the rules the layer needs). */')
    p('#include "rvhooks.h"')
    p()
    p('void host_thunk_enter(uint16_t fn, const char *name, int16_t nargs, const uint16_t *args);')
    p('void host_thunk_leave(uint16_t fn, const char *name, int16_t nargs, const uint16_t *args, uint16_t ret);')
    for f in funcs:
        ret = 'uint16_t' if f['ret'] == 'ax' else 'void'
        n = f['args']
        params = ', '.join('uint16_t a%d' % i for i in range(n)) or 'void'
        names = ', '.join('a%d' % i for i in range(n))
        p()
        p('%s %s(%s)' % (ret, f['name'], params))
        p('{')
        p('    uint16_t a[%d] = { %s };' % (max(n, 1), names or '0'))
        if ret != 'void':
            p('    uint16_t r;')
        p('    host_thunk_enter(RV_FN_%s, "%s", %d, a);' % (f['name'], f['name'], n))
        if ret != 'void':
            p('    r = %s_impl(%s);' % (f['name'], names))
            p('    host_thunk_leave(RV_FN_%s, "%s", %d, a, r);' % (f['name'], f['name'], n))
            p('    return r;')
        else:
            p('    %s_impl(%s);' % (f['name'], names))
            p('    host_thunk_leave(RV_FN_%s, "%s", %d, a, 0);' % (f['name'], f['name'], n))
        p('}')


def asm(consts, sections, items, funcs, sites):
    """RVHOOK and the fixed block, for nasm -f obj."""
    p = print
    p('; rvhook.asm: generated by tools/rvabi.py --asm from abi/rvabi.def: do not edit.')
    p('; RVHOOK (image paragraph 0, class RVHOOK): header, thunks, sites.  RVFIXED:')
    p('; the fixed block, DGROUP\'s first 0x%04X bytes (wlink orders it ahead of' % sections[-1]['start'])
    p('; Watcom\'s _NULL).  docs/spec.md sections 3-5, docs/engine.md.')
    p()
    p('        cpu 386')
    p('segment RVFIXED public align=16 class=BEGDATA use16')
    p('group DGROUP RVFIXED')
    p()
    for f in funcs:
        if f['name'] not in ASM_BODIES:
            p('        extern _%s_impl' % f['name'])
    p()
    p('segment RVHOOK public align=16 class=RVHOOK use16')
    p('rvhook_start:')
    p('        db "RVHOOK", 0, 0')
    p('        dw seg rvfixed_start              ; +8: DGROUP, relocated by DOS')
    p('        dw %d                              ; +10: ABI version' % ABI_VERSION)
    p('        dw %d                             ; +12: thunks' % len(funcs))
    p('        dw %d                             ; +14: sites' % len(sites))
    p('        times 0x20 - ($ - rvhook_start) db 0')
    for f in funcs:
        p('        global _%s' % f['name'])
        p('_%s:                                   ; 0x%04X' % (f['name'], f['off']))
        p('        jmp far _%s_impl' % f['name'])
    p('        times 0x400 - ($ - rvhook_start) db 0xCC')
    p('; The flight loop and its sites: hand-written in src/rvflight.inc, each site')
    p('; at the offset abi/rvabi.def fixes (RV_SITE_*), touching the fixed-block')
    p('; variables RV_DS_* (nasm -i src/).')
    byname = {it['name']: it for it in items}
    for st in sites:
        p('%%define RV_SITE_%s 0x%04X' % (st['name'], st['off']))
    for name in ('missionStatus', 'frameCounter'):
        p('%%define RV_DS_%s 0x%04X' % (name, byname[name]['off']))
    p('%include "rvflight.inc"')
    end = max([s['off'] for s in sites] + [0x400]) + 0x40
    p('        times 0x%04X - ($ - rvhook_start) db 0xCC' % end)
    p()
    p('segment RVFIXED')
    p('rvfixed_start:')
    p('        global _rv_fixed_block')
    p('_rv_fixed_block:')
    off = 0
    for it in items:
        if it['off'] > off:
            p('        times 0x%04X - ($ - rvfixed_start) db 0' % it['off'])
        p('; 0x%04X %s' % (it['off'], it['name']))
        if it['name'] == 'rvPuppetHeader':
            p('        db "RVPUPPET"')
            p('        dw %d, %d, %d, %d, %d' % (ABI_VERSION, consts['SLOTS'], consts['MAXSHIPSLOT'],
                                              consts['MAXSHIPSLOT'] + 1, consts['SLOTS'] - 3))
            p('        dw 0x%x, 0x%x, 0x33, 5, 0' % (byname['missionShipTable']['size'],
                                                   byname['navPointTable']['size']))
            p('        dd 0                           ; build number (the build stamps it)')
            p('        times 16 db 0                  ; build date')
        elif it['name'] == 'rvPuppetDirectory':
            offs = [i['off'] for i in items]
            for k in range(0, len(offs), 8):
                p('        dw ' + ', '.join('0x%04X' % o for o in offs[k:k + 8]))
        elif it['name'] == 'aLoadingWingCom':
            p('        db "%s", 0' % SIGNATURE)
        off_end = it['off'] + it['total']
        p('        times 0x%04X - ($ - rvfixed_start) db 0' % off_end)
        off = off_end
    p('        times 0x%04X - ($ - rvfixed_start) db 0' % sections[-1]['start'])


def print_tables(consts, sections, funcs, sites):
    for sec in sections[:-1]:
        print('**%s** 0x%04X-0x%04X (used to 0x%04X)\n' % (sec['name'], sec['start'],
              sections[sections.index(sec) + 1]['start'] - 1, sec['end']))
        print('| offset | name | element | count | bytes | note |')
        print('|---|---|---|---|---|---|')
        for it in sec['items']:
            n = consts['SLOTS'] if it['kind'] == 'SLOT' else it['count']
            print('| 0x%04X | %s | %d | %d | %d | %s |' % (it['off'], it['name'], it['size'], n,
                                                         it['total'], it['note']))
        print()
    print('**RVHOOK thunks** (image paragraph 0, far cdecl, 16-bit args)\n')
    print('| offset | function | args | returns | note |')
    print('|---|---|---|---|---|')
    for f in funcs:
        print('| 0x%04X | %s | %d | %s | %s |' % (f['off'], f['name'], f['args'], f['ret'], f['note']))
    print('\n**RVHOOK sites**\n')
    print('| offset | site | contract |')
    print('|---|---|---|')
    for s in sites:
        print('| 0x%04X | %s | %s |' % (s['off'], s['name'], s['note']))


if __name__ == '__main__':
    main()
